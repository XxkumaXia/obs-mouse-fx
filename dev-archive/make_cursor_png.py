#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
生成 obs-fx/cursor.png —— 纯数学绘制的中性箭头光标（32x32 单帧，热点 1,1）。

背景
----
仓库早期自带的 cursor.png 是从第三方鼠标主题（8 帧 .ani）里解出来的，
版权不明，不适合放进开源仓库。这张图由本脚本绘制：
白填充 + 黑描边，轮廓取自经典的 7 点箭头多边形，无任何第三方素材。

为什么不用 Pillow
-----------------
开发机上不保证装了 Pillow，而这个脚本只需要画一张 32x32 的图。
所以 PNG 编码器也是手写（zlib + struct，标准库够用）。

用法
----
    python make_cursor_png.py                  # 写到 ../obs-fx/cursor.png
    python make_cursor_png.py 输出路径.png      # 或指定路径

绘制思路
--------
先算每个采样点到多边形边界的**有符号距离**（内部为负），再按距离上色：
    内部深处        -> 白色填充
    边界附近        -> 黑色描边（保证在任何画面上都看得清）
    边界外一小圈    -> 黑色并做抗锯齿衰减
最后 4x4 超采样，得到干净的边缘。
"""

import math
import os
import struct
import sys
import zlib

SIZE = 32          # 画布 / 单帧尺寸
SS = 4             # 每像素超采样数（SS x SS）
HOT = (1, 1)       # 热点（Picture 左上角到箭尖的像素偏移），与脚本默认值一致

# 经典箭头轮廓（顺时针）。热点在左上角 (1,1)，即箭尖略靠内 1px 处。
POLY = [
    (1.0, 1.0),
    (1.0, 22.5),
    (5.4, 18.2),
    (9.2, 25.4),
    (14.0, 24.0),
    (10.0, 16.4),
    (17.4, 16.4),
]

# 描边宽度参数（单位：像素，负号侧为形状内部）
INNER_LINE = 0.75   # 向内多少像素算黑边
OUTER_LINE = 1.15   # 向外多少像素还在描边的抗锯齿范围


def point_in_poly(px, py, poly):
    """射线法判断点是否在多边形内部。"""
    inside = False
    n = len(poly)
    j = n - 1
    for i in range(n):
        xi, yi = poly[i]
        xj, yj = poly[j]
        # 边跨越当前水平线，且交点在点的右侧 -> 奇偶翻转
        if (yi > py) != (yj > py):
            x_cross = xi + (py - yi) * (xj - xi) / float(yj - yi)
            if px < x_cross:
                inside = not inside
        j = i
    return inside


def dist_to_seg(px, py, ax, ay, bx, by):
    """点到线段的最短距离。"""
    dx, dy = bx - ax, by - ay
    if dx == 0.0 and dy == 0.0:
        return math.hypot(px - ax, py - ay)
    t = ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)
    t = max(0.0, min(1.0, t))
    return math.hypot(px - (ax + t * dx), py - (ay + t * dy))


def signed_dist(px, py, poly):
    """有符号距离：内部为负，外部为正，绝对值 = 到最近边的距离。"""
    n = len(poly)
    d = min(dist_to_seg(px, py, poly[i][0], poly[i][1],
                        poly[(i + 1) % n][0], poly[(i + 1) % n][1])
            for i in range(n))
    return -d if point_in_poly(px, py, poly) else d


def sample_rule(sd):
    """按有符号距离决定颜色：返回 (白alpha, 黑alpha)。"""
    if sd <= -INNER_LINE:
        return 1.0, 0.0                       # 内部填充：白
    if sd <= 0.15:
        return 0.0, 1.0                       # 描边主体：黑
    if sd <= OUTER_LINE:
        return 0.0, (OUTER_LINE - sd) / (OUTER_LINE - 0.15)   # 外沿抗锯齿
    return 0.0, 0.0                           # 完全透明


def render(size=SIZE, ss=SS):
    """渲染一张 RGBA 位图，返回打包好的字节流（自上而下，每行 RGBA）。"""
    rows = []
    step = 1.0 / ss
    off = step / 2.0
    for y in range(size):
        row = bytearray()
        for x in range(size):
            acc_w = acc_b = 0.0
            for sy in range(ss):
                py = y + off + sy * step
                for sx in range(ss):
                    px = x + off + sx * step
                    w, b = sample_rule(signed_dist(px, py, POLY))
                    # 同一次采样里黑白互斥，先白后黑做一次 source-over
                    a = b + w * (1.0 - b)
                    acc_b += b
                    acc_w += w * (1.0 - b)
                    _ = a
            n = float(ss * ss)
            a_b = acc_b / n
            a_w = acc_w / n
            a = a_b + a_w * (1.0 - a_b)       # 合成后的总 alpha
            if a <= 0.0:
                row += b"\x00\x00\x00\x00"
                continue
            # 预乘色：黑占 a_b，白占 a_w*(1-a_b)，还原为非预乘 RGB
            lum = (a_w * (1.0 - a_b)) / a     # 白色在最终颜色里的占比
            v = int(round(255.0 * lum))
            row += bytes((v, v, v, int(round(255.0 * a))))
        rows.append(bytes(row))
    return b"".join(rows)


def write_png(path, size, raw, hot=HOT):
    """手写 PNG 写出（RGBA8）。顺便把热点写进 tEXt 注释，方便人确认。"""
    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0)
    # 每行前置 filter byte = 0（None）
    scan = b"".join(b"\x00" + raw[i * size * 4:(i + 1) * size * 4]
                    for i in range(size))
    png = (b"\x89PNG\r\n\x1a\n"
           + chunk(b"IHDR", ihdr)
           + chunk(b"tEXt", b"Comment\0generated by make_cursor_png.py; "
                            b"hotspot %d,%d" % hot)
           + chunk(b"IDAT", zlib.compress(scan, 9))
           + chunk(b"IEND", b""))
    with open(path, "wb") as f:
        f.write(png)
    return len(png)


def main():
    if len(sys.argv) > 1:
        out = sys.argv[1]
    else:
        out = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "..", "obs-fx", "cursor.png")
    out = os.path.normpath(out)
    size_n = write_png(out, SIZE, render())
    print("已生成 %s（%dx%d 单帧 RGBA，热点 %d,%d，%d 字节）"
          % (out, SIZE, SIZE, HOT[0], HOT[1], size_n))


if __name__ == "__main__":
    main()
